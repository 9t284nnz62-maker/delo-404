@app.route("/")
def index():
    return render_template("index.html")

@app.route("/case")
def case():
    studied = session.get("studied", [])
    return render_template("case.html", materials=MATERIALS, studied=studied)

@app.route("/study/<mid>")
def study(mid):
    studied = session.get("studied", [])
    if mid not in studied:
        studied.append(mid)
    session["studied"] = studied
    return render_template("material.html", material=MATERIALS[mid])

@app.route("/accuse", methods=["GET", "POST"])
def accuse():
    if request.method == "POST":
        session["accused"] = request.form.get("suspect")
        return redirect(url_for("result"))
    return render_template("accuse.html", suspects=SUSPECTS)

@app.route("/result")
def result():
    accused = session.get("accused")
    studied = session.get("studied", [])
    win = accused == "maxim" and all(m in studied for m in ["m2", "m5", "m8"])
    return render_template("result.html", win=win, accused=accused)

@app.route("/reset")
def reset():
    session.clear()
    return redirect(url_for("index"))

